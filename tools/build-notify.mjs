/* Builds notify-function.ts = engine.js + notify-handler.ts, so the server scores exactly like the site.
   Run after changing engine.js or tools/notify-handler.ts:  node tools/build-notify.mjs */
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const engine = readFileSync(new URL("engine.js", root), "utf8").replace(/^export /gm, "");
const handler = readFileSync(new URL("tools/notify-handler.ts", root), "utf8");
const imports = handler.match(/^import .*$/gm).join("\n");
writeFileSync(new URL("notify-function.ts", root), `// @ts-nocheck
// Supabase Edge Function "notify" for Side Gains. GENERATED by tools/build-notify.mjs, don't edit by hand.
// Deploy with JWT verification OFF: the database schedule calls it without a login, and it checks logins itself.
${imports}

${engine}
${handler.replace(/^import .*\n/gm, "")}`);
console.log("notify-function.ts written");
